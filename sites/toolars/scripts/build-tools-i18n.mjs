// Build namespace for each locale
function buildToolsNS(translations, locale) {
  const ns = {};
  for (const slug of slugs) {
    const en = enTools[slug];
    ns[slug] = {
      name: en.name,
      description: translations[slug] || en.description
    };
  }
  return ns;
}

// Merge into messages files
for (const locale of ["en", "es", "zh"]) {
  const path = `messages/${locale}.json`;
  const messages = JSON.parse(readFileSync(path, "utf8"));
  const translations = locale === "en" ? Object.fromEntries(slugs.map(s => [s, enTools[s].description])) : (locale === "es" ? es : zh);
  messages.tools = buildToolsNS(translations, locale);
  writeFileSync(path, JSON.stringify(messages, null, 2) + "\n");
  console.log(`${locale}.json: added ${slugs.length} tools`);
}
